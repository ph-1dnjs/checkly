test('upload paths remain on this PC while DB stores a reusable scenario', async ({ page }) => {
  await installAuthStub(page, { enabled: true, session: owner })
  await editor(page)
  const source = page.getByRole('textbox', { name: '시나리오 Markdown 원본' })
  const upload = markdown + '\nAnd `첨부`에 `/Users/test/private.pdf` 파일 업로드'
  await source.fill(upload)
  await page.getByRole('button', { name: '저장', exact: true }).click()
  await expect(page.getByText('UNSAVED', { exact: true })).toHaveCount(0)
  const saved = (await authCalls(page)).find(([name]) => name === 'webScenarios.save')![1]
  expect(JSON.stringify(saved)).not.toContain('/Users/test')
  await page.reload()
  await page.getByRole('button', { name: '시나리오 · 편집과 실행' }).click()
  await page.getByRole('tab', { name: '편집' }).click()
  await page.locator('.scenario-files button').filter({ hasText: '팀 로그인' }).click()
  await expect(source).toHaveValue(/`첨부`에 `\/Users\/test\/private.pdf` 파일 업로드/)
})

test('marker edits save together with the body and use the chosen environment', async ({ page }) => {
  await installAuthStub(page, { enabled: true, session: owner })
  await editor(page)
  const source = page.getByRole('textbox', { name: '시나리오 Markdown 원본' })
  await source.fill(markdown)
  await page.getByRole('button', { name: '저장', exact: true }).click()
  await expect(page.getByText('UNSAVED', { exact: true })).toHaveCount(0)
  // JSONB가 키 순서를 바꿔 돌려줘도 수정 전 상태는 깨끗하고 좌표는 유지되어야 한다.
  await page.evaluate(() => {
    const rows = JSON.parse(sessionStorage.getItem('web-scenarios')!)
    rows[0].positions = JSON.stringify({ '팀 로그인\n/login': [{ y: 20, x: 10, target: '로그인', action: 'click' }] })
    sessionStorage.setItem('web-scenarios', JSON.stringify(rows))
  })
  await page.locator('.scenario-files').getByRole('button', { name: '새로고침' }).click()
  await expect(page.getByText('UNSAVED', { exact: true })).toHaveCount(0)
  await page.getByLabel('시나리오 환경').selectOption('v-stg')
  await page.getByRole('button', { name: '화면 추출', exact: true }).click()
  await expect(page.locator('webview')).toHaveAttribute('src', 'https://stg.app.com/login')
  await page.getByLabel('대상 URL').fill('/updated')
  await page.getByRole('button', { name: '텍스트', exact: true }).click()
  await page.getByRole('button', { name: '저장 후 돌아가기' }).click()
  await expect(source).toHaveValue(/url: \/updated/)
  await expect(page.getByText('UNSAVED', { exact: true })).toHaveCount(0)
  const saves = (await authCalls(page)).filter(([name]) => name === 'webScenarios.save')
  expect(saves).toHaveLength(2)
  expect(Object.values(JSON.parse(saves[1][1].positions)).flat()[0]).toMatchObject({ x: 10, y: 20 })
  await page.screenshot({ path: '/tmp/checkly-db-editor.png', fullPage: true })
})

test('shared DB list preserves selections across documents and shows the existing step and run summary UI', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 960 })
  await installAuthStub(page, { enabled: true, session: owner })
  await editor(page)
  const source = page.getByRole('textbox', { name: '시나리오 Markdown 원본' })
  await source.fill(markdown + '\n\n# 시나리오: 로그아웃\nurl: /logout\n\nGiven `로그아웃` 클릭')
  await page.getByRole('button', { name: '저장', exact: true }).click()
  await expect(page.getByText('UNSAVED', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '새 시나리오', exact: true }).click()
  await source.fill(markdown.replace('팀 로그인', '프로필'))
  await page.getByRole('button', { name: /^(저장|저장됨)$/ }).click()
  await expect(page.getByText('UNSAVED', { exact: true })).toHaveCount(0)
  await page.getByRole('tab', { name: '실행', exact: true }).click()
  const list = page.locator('.scenario-files')
  await list.getByRole('button', { name: /팀 로그인/ }).click()
  await page.getByRole('checkbox', { name: '전체 선택' }).click()
  await expect(list.locator('em')).toHaveText('2 선택')
  await page.locator('.picker-expand').first().click()
  await expect(page.locator('.picker-steps .action-tag')).toHaveCount(1)
  await list.getByRole('button', { name: /프로필/ }).click()
  await page.locator('.picker-scenario-main[aria-pressed]').click()
  await expect(page.locator('.picker-cart-item')).toHaveCount(3)
  await expect(page.locator('.picker-cart-stats strong')).toHaveText(['3', '3'])
  await list.getByRole('button', { name: /팀 로그인/ }).click()
  await page.getByRole('checkbox', { name: '전체 선택' }).click()
  await expect(page.locator('.picker-cart-item')).toHaveCount(1)
  await expect(page.locator('.picker-cart-item')).toContainText('프로필')
  await page.screenshot({ path: '/tmp/checkly-db-picker-reuse.png', fullPage: true })
  await page.setViewportSize({ width: 860, height: 900 })
  await expect(list).toBeVisible()
  await list.getByRole('button', { name: /프로필/ }).click()
  await expect(page.locator('.picker-scenario-name')).toHaveText('프로필')
})
