import { expect, test } from '@playwright/test'
import { authCalls, installAuthStub, owner } from './fixtures/auth-stub'

const markdown = '# 시나리오: 팀 로그인\nendpoint: e-web\n\nGiven `로그인` 클릭'
// 시나리오 환경은 API 테스트와 같은 환경 메뉴(EnvironmentMenu)로 고른다.
const chooseEnvironment = async (page: import('@playwright/test').Page, name: string) => {
  await page.getByRole('button', { name: '시나리오 환경' }).click()
  await page.getByRole('menu', { name: '환경 선택' }).getByRole('menuitemradio', { name: new RegExp(`^${name}`) }).click()
}

const editor = async (page: import('@playwright/test').Page) => {
  await page.goto('/')
  await page.getByRole('button', { name: '시나리오 · 편집과 실행' }).click()
  await page.getByRole('tab', { name: '편집' }).click()
}

test('DB CRUD persists across reload, protects drafts and removes file controls', async ({ page }) => {
  await installAuthStub(page, { enabled: true, session: owner })
  await editor(page)
  await expect(page.getByRole('button', { name: /폴더|불러오기|새로 저장하기/ })).toHaveCount(0)
  await page.getByRole('button', { name: '새 시나리오', exact: true }).click()
  const source = page.getByRole('textbox', { name: '시나리오 Markdown 원본' })
  await source.fill(markdown)
  await page.getByRole('button', { name: '저장', exact: true }).click()
  await expect(page.getByText('저장 안 됨', { exact: true })).toHaveCount(0)
  await expect(page.locator('.scenario-files')).toContainText('minsu')
  await page.reload()
  await page.getByRole('button', { name: '시나리오 · 편집과 실행' }).click()
  await page.getByRole('tab', { name: '편집' }).click()
  await page.locator('.scenario-files button').filter({ hasText: '팀 로그인' }).click()
  await expect(source).toHaveValue(/# 시나리오: 팀 로그인[\s\S]*Given `로그인` 클릭/)
  await expect(page.getByText('저장 안 됨', { exact: true })).toHaveCount(0)
  await source.fill(markdown.replace('팀 로그인', '수정된 로그인'))
  await page.getByRole('button', { name: '새 시나리오', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: '취소' }).click()
  await expect(source).toHaveValue(/수정된 로그인/)
  await page.getByRole('button', { name: '저장', exact: true }).click()
  await expect(page.locator('.scenario-files')).toContainText('수정된 로그인')
  await page.getByRole('tab', { name: '실행', exact: true }).click()
  await expect(page.locator('.picker-scenario-name')).toHaveText('수정된 로그인')
  await page.getByRole('tab', { name: '편집', exact: true }).click()
  await page.getByRole('button', { name: '더보기' }).click()
  await page.getByRole('menuitem', { name: '문서 삭제' }).click()
  await page.getByRole('dialog', { name: '시나리오 삭제' }).getByRole('button', { name: '삭제', exact: true }).click()
  await expect(page.locator('.scenario-files')).toContainText('저장된 시나리오가 없습니다')
  const calls = await authCalls(page)
  expect(calls.filter(([name]) => name === 'webScenarios.save')).toHaveLength(2)
  const update = calls.filter(([name]) => name === 'webScenarios.save')[1][1]
  expect(update.id).toBeTruthy()
  expect(update.expectedUpdatedAt).toBeTruthy()
})

